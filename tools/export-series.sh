#!/bin/bash
# Export a series to patches/<version>/<name>/.
#
# Usage: tools/export-series.sh [--summary] [--rev <commit>] <name>
#
# Exports the commits between the stable tag the series is based on and the
# tip of the series: the submodule HEAD, or <commit> with --rev. The patch
# files, series, source and README.md in the target directory are generated
# and replaced on every run. Nothing is committed and the submodule pin is
# not changed.
#
# With --summary, also write a commit message to build/export-message.txt
# (use with git commit -F). If HEAD pins the series in the same kernel
# series, it lists the patches that were added, removed or changed since
# that pin (git range-diff).

source "$(dirname "$0")/lib.sh"

summary= rev=HEAD
while (($#)); do
	case $1 in
	--summary) summary=1 ;;
	--rev)
		rev=${2-}
		shift
		;;
	-*) die "unknown option: $1" ;;
	*) break ;;
	esac
	shift
done
(($# == 1)) || die "usage: $0 [--summary] [--rev <commit>] <name>"
load_series "$1"

head=$("${GIT[@]}" rev-parse --verify "$rev^{commit}")
base=$(base_of "$head")
merges=$("${GIT[@]}" rev-list --count --merges "$base..$head")
((merges == 0)) || die "$NAME has $merges merge commits on top of $base, format-patch would drop them"

OUT="$TOP/patches/$VERSION/$NAME"
mkdir -p "$OUT"
find "$OUT" -maxdepth 1 -name '*.patch' -delete

# --zero-commit, --no-signature and --no-numbered keep re-exports free of
# noise: a patch file only changes when the patch itself changes.
"${GIT[@]}" format-patch -q --zero-commit --no-signature --no-numbered \
	-o "$OUT" "$base..$head"
(cd "$OUT" && ls -1 -- *.patch) >"$OUT/series"
count=$(wc -l <"$OUT/series")

{
	echo "branch=$BRANCH"
	echo "base=$base"
	echo "head=$head"
	echo "date=$("${GIT[@]}" log -1 --format=%cs "$head")"
	[[ -z $PR ]] || echo "pr=$PR"
} >"$OUT/source"

{
	echo "# $NAME for Linux $VERSION"
	echo
	echo "Generated by \`tools/export-series.sh\` from branch \`$BRANCH\`"
	echo "($count patches on top of the stable tag \`$base\`)."
	echo "Do not edit; change the branch and re-export."
	echo
	echo "Apply with \`git am patches/$VERSION/$NAME/*.patch\` on \`$base\` or a later"
	echo "$VERSION stable release."
	if [[ -n $PR ]]; then
		echo
		echo "Discussion: [kakra/linux PR $PR](https://github.com/kakra/linux/pull/$PR)"
	fi
	echo
	echo "| # | Patch | Author |"
	echo "|---|---|---|"
	n=0
	"${GIT[@]}" log --reverse --format='%an%x09%s' "$base..$head" |
		while IFS=$'\t' read -r author subject; do
			n=$((n + 1))
			file=$(sed -n "${n}p" "$OUT/series")
			printf '| %d | [%s](%s) | %s |\n' "$n" "${subject//|/\\|}" "$file" "$author"
		done
} >"$OUT/README.md"

echo "Exported $count patches on $base to ${OUT#"$TOP"/}"

[[ -n $summary ]] || exit 0

MSG="$TOP/build/export-message.txt"
mkdir -p "$TOP/build"
old=$(git -C "$TOP" rev-parse -q --verify "HEAD:series/$NAME" || true)
old_version=
if [[ -n $old ]]; then
	old_version=$(git -C "$TOP" config --blob HEAD:.gitmodules "submodule.$NAME.branch" || true)
	old_version=${old_version:+$(version_of_branch "$old_version")}
fi
{
	if [[ -n $old && $old_version == "$VERSION" ]]; then
		"${GIT[@]}" cat-file -e "$old^{commit}" 2>/dev/null ||
			die "old pin ${old:0:12} is not available (fetch it, or write the message by hand)"
		echo "patches: update $NAME for $VERSION"
		echo
		echo "Changes to $BRANCH (git range-diff ${old:0:12}...${head:0:12}):"
		echo
		"${GIT[@]}" range-diff --no-color "$(base_of "$old")..$old" "$base..$head" |
			grep -E '^ *([0-9]+|-): +([0-9a-f]+|-+) [!<>] ' || echo "Only the base changed."
	else
		echo "patches: export $NAME for $VERSION"
		echo
		echo "Pin series/$NAME to $BRANCH (${head:0:12}, $count patches on" \
			"$base) and export it to patches/$VERSION/$NAME/." | fold -s -w 72 | sed 's/ *$//'
	fi
	if [[ -n $PR ]]; then
		echo
		echo "References:"
		echo "- kakra/linux PR $PR"
	fi
} >"$MSG"
echo "Commit message written to ${MSG#"$TOP"/}"
